let currentLang = localStorage.getItem('selectedLang') || 'en';

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('selectedLang', lang);
    
    const data = translations[lang];
    Object.keys(data).forEach(id => {
        const el = document.getElementById(id);
        if (el) el.textContent = data[id];
    });
    document.getElementById('langMenu').classList.remove('show');
    updateButtons(); // Refresh navigation after language change
}

function navigateToPage(pageKey) {
    const pageFile = langPages[pageKey][currentLang] || langPages[pageKey].en;
    window.location.href = pageFile;
}

function toggleLangMenu() {
    document.getElementById('langMenu').classList.toggle('show');
}

function updateButtons() {
    const buttons = {
        'btn-life': 'life', 
        'btn-term': 'term', 
        'btn-health': 'health',
        'btn-crop': 'crop', 
        'btn-travel': 'travel', 
        'btn-mf': 'mf',
        'btn-motor': 'motor',
        'btn-invest': 'invest' // Add this line
    };
    
    Object.entries(buttons).forEach(([btnId, pageKey]) => {
        const btn = document.getElementById(btnId);
        if (btn) {
            btn.onclick = () => navigateToPage(pageKey);
            btn.textContent = translations[currentLang][btnId] || btn.textContent;
        }
    });
}


// FIXED Language detection
function getLangFromButton(text) {
    const lower = text.toLowerCase();
    if (lower.includes('हिं') || lower.includes('hindi')) return 'hi';
    if (lower.includes('मराठी') || lower.includes('marathi')) return 'mr';
    if (lower.includes('తె') || lower.includes('telugu')) return 'te';
    if (lower.includes('ଓ') || lower.includes('odia')) return 'or';
    return 'en';
}

// Initialize
document.addEventListener('DOMContentLoaded', () => {
    if (currentLang !== 'en') changeLanguage(currentLang);
    
    // Language buttons (CORRECTED)
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.onclick = (e) => {
            e.stopPropagation();
            const lang = getLangFromButton(e.target.textContent);
            changeLanguage(lang);
        };
    });
    
    window.onclick = function(event) {
        if (!event.target.matches('.lang-btn-trigger') && !event.target.closest('.lang-dropdown-wrapper')) {
            document.getElementById('langMenu').classList.remove('show');
        }
    };
});
function triggerThemeAnimation() {
    const cards = document.querySelectorAll('.glass-card');
    
    // Briefly hide cards
    cards.forEach(card => card.style.opacity = '0');

    setTimeout(() => {
        // Show cards with a smooth fade-in
        cards.forEach((card, index) => {
            setTimeout(() => {
                card.style.opacity = '1';
                card.style.transform = 'translateY(0)';
            }, index * 50); // Staggered delay for each card
        });
    }, 300);
}

function enableLightMode() {
    triggerThemeAnimation();
    body.classList.add('light-mode');
    themeIcon.classList.replace('fa-moon', 'fa-sun');
    themeText.textContent = "Light Mode";
    localStorage.setItem('theme', 'light');
}

function enableDarkMode() {
    triggerThemeAnimation();
    body.classList.remove('light-mode');
    themeIcon.classList.replace('fa-sun', 'fa-moon');
    themeText.textContent = "Dark Mode";
    localStorage.setItem('theme', 'dark');
}